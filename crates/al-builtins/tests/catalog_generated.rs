//! `catalog/signatures.txt` must be exactly what the pinned corpus's docs
//! scrape generates. Regenerate with `UPDATE_GOLDEN=1 cargo test -p al-builtins`.

use std::path::Path;

#[test]
fn signatures_file_is_up_to_date_with_the_pinned_corpus() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let json = std::fs::read_to_string(root.join("../../corpus/scripts/al-surface.json"))
        .expect("corpus submodule not checked out: run `git submodule update --init`");
    let lines = al_builtins::catalog::generate(&json).unwrap_or_else(|e| panic!("unparseable syntax lines:\n{e}"));
    let generated = format!(
        "# GENERATED from corpus/scripts/al-surface.json by al-builtins (ADR-008). Do not edit; use overrides.txt.\n{}\n",
        lines.join("\n")
    );
    let path = root.join("catalog/signatures.txt");
    if std::env::var_os("UPDATE_GOLDEN").is_some() {
        std::fs::write(&path, &generated).unwrap();
    }
    assert_eq!(
        std::fs::read_to_string(&path).unwrap_or_default(),
        generated,
        "stale; rerun with UPDATE_GOLDEN=1"
    );
}

/// `catalog/alc-runtimes.txt` (what the AL compiler reports for each overload at each runtime, generated by
/// `tools/alc-runtimes/alc_runtimes.py`, al-runner issue 5573) has a row for every catalog line and every argument
/// count it accepts. A row may say that no probe expresses the call (`-`); this test lists those, so a new catalog
/// line without a measurement fails here until the generator is rerun.
#[test]
fn the_alc_runtimes_table_covers_every_catalog_overload() {
    let c = al_builtins::catalog::Catalog::load();
    let missing: Vec<String> = c
        .alc_coverage()
        .into_iter()
        .filter(|(_, _, has)| !has)
        .map(|(l, n, _)| format!("{l} [{n} arguments]"))
        .collect();
    assert!(
        missing.is_empty(),
        "no row in catalog/alc-runtimes.txt (rerun tools/alc-runtimes/alc_runtimes.py):\n{}",
        missing.join("\n")
    );
    // Every row is a catalog line (a stale row would hide a renamed or removed overload).
    let lines: std::collections::HashSet<String> = c.signatures.iter().map(|s| s.to_line()).collect();
    let text = include_str!("../catalog/alc-runtimes.txt");
    let stale: Vec<&str> = text
        .lines()
        .filter(|l| !l.starts_with('#'))
        .filter_map(|l| l.split('\t').next())
        .filter(|l| !lines.contains(*l))
        .collect();
    assert!(stale.is_empty(), "rows of no catalog line:\n{}", stale.join("\n"));
}

#[test]
fn digit_codes_on_decimal_places_fields() {
    for (spec, len, rows, amt27, amt28) in R6901_CASES {
        for n in 1..=9usize {
            let call_row = |bc: &str, amount: bool| match call(
                bc,
                "R6901",
                vec![
                    Value::Text((*spec).into()),
                    Value::Integer(*len),
                    Value::Integer(n as i32),
                    Value::Boolean(amount),
                ],
            ) {
                Ok(Value::Text(t)) => t.to_string(),
                other => panic!("{spec} len {len} row {n} amount {amount}: {other:?}"),
            };
            for bc in ["27.0", "28.0", "29.0"] {
                assert_eq!(call_row(bc, false), rows[n - 1], "{bc} {spec} len {len} row {n}");
            }
            assert_eq!(
                call_row("27.0", true),
                amt27[n - 1],
                "27.0 amount {spec} len {len} row {n}"
            );
            for bc in ["28.0", "29.0"] {
                assert_eq!(call_row(bc, true), amt28[n - 1], "{bc} amount {spec} len {len} row {n}");
            }
        }
    }
}

#[test]
fn precision_first_without_standard_format_stays_refused_for_other_places() {
    // Only `<Precision,2:4><Integer><Decimal>` is pinned (language/R6901DecimalFieldFormat.al:810-850 R6901_PrecisionControl_*).
    let r = call(
        "29.0",
        "R6901",
        vec![
            Value::Text("<Precision,2:3><Integer><Decimal>".into()),
            Value::Integer(0),
            Value::Integer(4),
            Value::Boolean(false),
        ],
    );
    assert!(matches!(r, Err(Signal::Unsupported(_))), "{r:?}");
}

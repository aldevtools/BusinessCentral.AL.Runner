//! Function length ratchet. A `fn` body in a Rust file under `crates/*/src` may not exceed
//! `LIMIT` lines, except the functions listed in `metrics/fn-lengths.toml`, each of which may not
//! grow past its own cap. A cap only goes down: extract steps into functions of their own and
//! lower or delete the row. Raising a cap or adding a row needs the owner.
//!
//! A body's length is the number of lines from its `{` to its `}` (both included) that hold code:
//! blank lines and lines that hold only a comment do not count. Nested functions and closures
//! count in the function around them; a nested `fn` is also measured on its own.
//!
//! A row is keyed `"path::name"`, not by line number, so edits elsewhere in the file do not move
//! it. When one file holds several functions of one name over the limit (methods of different
//! `impl` blocks), the second in source order is `"path::name#2"`, the third `#3`, and so on;
//! functions of that name within the limit get no ordinal.
//!
//! Exempt: generated files (one of the first five lines holds `@generated` or `Generated by`)
//! and everything under `crates/*/tests`, `crates/*/examples` and `crates/*/benches`.

mod rust_scan;

use rust_scan::{blank, code_lines, fn_bodies, is_generated, line_of, line_starts, parse_table};
use std::collections::BTreeMap;

const LIMIT: usize = 250;
const TABLE: &str = "metrics/fn-lengths.toml";

/// The functions of one file over `LIMIT`, as (key, length), keyed as the module doc says.
fn long_fns(path: &str, src: &str) -> Vec<(String, usize)> {
    let code = blank(src);
    let starts = line_starts(&code);
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    let mut out = Vec::new();
    for f in fn_bodies(&code) {
        let from = line_of(&starts, f.open);
        let to = line_of(&starts, f.close.min(code.len().saturating_sub(1)));
        let len = code_lines(&code, &starts, from, to);
        if len <= LIMIT {
            continue;
        }
        let k = seen.entry(f.name.clone()).or_default();
        *k += 1;
        let key = if *k == 1 {
            format!("{path}::{}", f.name)
        } else {
            format!("{path}::{}#{k}", f.name)
        };
        out.push((key, len));
    }
    out
}

/// Failure messages for the long functions found against the table.
fn violations(found: &[(String, usize)], caps: &BTreeMap<String, usize>) -> Vec<String> {
    let mut out = Vec::new();
    for (key, len) in found {
        match caps.get(key) {
            None => out.push(format!(
                "{key}: {len} lines, limit {LIMIT}. Extract steps into functions of their own \
                 instead of listing it; adding a row to {TABLE} needs the owner."
            )),
            Some(cap) if len > cap => out.push(format!(
                "{key}: {len} lines, cap {cap}. Extract steps into functions of their own \
                 instead of raising the cap; raising a cap needs the owner."
            )),
            _ => {}
        }
    }
    for key in caps.keys() {
        if !found.iter().any(|(k, _)| k == key) {
            out.push(format!(
                "{key}: listed in {TABLE} but no function of that key is over {LIMIT} lines \
                 (it shrank, was renamed or was removed); delete the row."
            ));
        }
    }
    out
}

/// Notes for listed functions that shrank but are still over the limit: the cap should follow.
fn lowerable(found: &[(String, usize)], caps: &BTreeMap<String, usize>) -> Vec<String> {
    found
        .iter()
        .filter_map(|(key, len)| {
            let cap = caps.get(key)?;
            (len < cap).then(|| format!("{key}: now {len} lines; lower its cap from {cap} to {len} in {TABLE}"))
        })
        .collect()
}

fn all_long_fns() -> Vec<(String, usize)> {
    let root = rust_scan::root();
    let mut crates: Vec<_> = std::fs::read_dir(root.join("crates"))
        .unwrap()
        .map(|e| e.unwrap().path())
        .collect();
    crates.sort();
    let mut out = Vec::new();
    for krate in crates {
        for (path, text) in rust_scan::rust_files(&krate.join("src"), &root) {
            if !is_generated(&text) {
                out.extend(long_fns(&path, &text));
            }
        }
    }
    out
}

#[test]
fn no_function_grows_past_its_cap() {
    let root = rust_scan::root();
    let table = std::fs::read_to_string(root.join(TABLE)).unwrap_or_else(|e| panic!("{TABLE}: {e}"));
    let caps = parse_table(TABLE, &table);
    let found = all_long_fns();
    if std::env::var_os("PRINT_FN_LENGTHS").is_some() {
        for (key, len) in &found {
            println!("\"{key}\" = {len}");
        }
    }
    for note in lowerable(&found, &caps) {
        eprintln!("note: {note}");
    }
    let bad = violations(&found, &caps);
    assert!(bad.is_empty(), "function length ratchet:\n{}", bad.join("\n"));
}

/// A function whose body has `lines` code lines.
fn body(name: &str, lines: usize) -> String {
    let mut s = format!("fn {name}() {{\n");
    for i in 0..lines.saturating_sub(2) {
        s += &format!("    let _x{i} = {i};\n");
    }
    s + "}\n"
}

#[test]
fn a_function_at_the_limit_passes_and_one_over_fails() {
    assert!(long_fns("a.rs", &body("ok", LIMIT)).is_empty());
    let found = long_fns("crates/a/src/x.rs", &body("big", LIMIT + 1));
    assert_eq!(found, vec![("crates/a/src/x.rs::big".to_string(), LIMIT + 1)]);
    let bad = violations(&found, &BTreeMap::new());
    assert_eq!(bad.len(), 1);
    assert!(
        bad[0].contains("crates/a/src/x.rs::big: 251 lines, limit 250"),
        "{bad:?}"
    );
}

#[test]
fn blank_and_comment_lines_do_not_count() {
    let src = "fn f() {\n\n    // one\n    /* two\n       three */\n    let a = 1; // trailing\n\n}\n";
    let code = blank(src);
    let starts = line_starts(&code);
    let f = &fn_bodies(&code)[0];
    assert_eq!(f.name, "f");
    let lines = code_lines(&code, &starts, line_of(&starts, f.open), line_of(&starts, f.close));
    assert_eq!(lines, 3, "the brace lines and `let a`");
}

#[test]
fn braces_in_literals_and_comments_are_not_code() {
    let src = r####"fn f() {
    let a = "}";
    let b = '}';
    let c = r#"} " }"#;
    let d = b'{';
    let e = br##"}"##;
    let g = "\"}\\";
    // }
    /* } /* nested } */ } */
    let l: &'static str = "x";
    'outer: loop { break 'outer; }
}
fn after() {}
"####;
    let names: Vec<_> = fn_bodies(&blank(src)).into_iter().map(|f| f.name).collect();
    assert_eq!(names, ["f", "after"]);
    let code = blank(src);
    let f = &fn_bodies(&code)[0];
    let starts = line_starts(&code);
    assert_eq!(
        line_of(&starts, f.close),
        11,
        "the closing brace of f is on its last line"
    );
}

#[test]
fn declarations_fn_types_and_parameter_patterns() {
    let src = "trait T { fn decl(&self); fn with_body(&self) { } }\n\
               fn takes(cb: fn(u8) -> u8, Point { x, y }: Point) -> impl Fn() { || {} }\n\
               fn r#match() {}\n\
               let s = \"fn not_code() {}\";\n";
    let names: Vec<_> = fn_bodies(&blank(src)).into_iter().map(|f| f.name).collect();
    assert_eq!(names, ["with_body", "takes", "match"]);
}

#[test]
fn nested_functions_are_measured_alone_and_in_their_parent() {
    let inner = body("inner", LIMIT + 1);
    let src = format!("fn outer() {{\n{inner}}}\n");
    let keys: Vec<_> = long_fns("p.rs", &src).into_iter().map(|(k, _)| k).collect();
    assert_eq!(keys, ["p.rs::outer", "p.rs::inner"]);
}

#[test]
fn same_name_functions_over_the_limit_get_ordinals() {
    let src = format!(
        "impl A {{ {} }}\nimpl B {{ {} }}\nimpl C {{ {} }}\n",
        body("new", LIMIT + 1),
        body("new", 3),
        body("new", LIMIT + 5)
    );
    let found = long_fns("p.rs", &src);
    assert_eq!(
        found,
        vec![
            ("p.rs::new".to_string(), LIMIT + 1),
            ("p.rs::new#2".to_string(), LIMIT + 5)
        ]
    );
}

#[test]
fn a_listed_function_may_not_grow_but_may_shrink() {
    let caps = parse_table(TABLE, "# comment\n\"p.rs::big\" = 400 # why\n\"p.rs::new#2\" = 300\n");
    assert_eq!(caps.get("p.rs::new#2"), Some(&300));
    let grown = [("p.rs::big".to_string(), 401), ("p.rs::new#2".to_string(), 300)];
    let bad = violations(&grown, &caps);
    assert_eq!(bad.len(), 1, "{bad:?}");
    assert!(bad[0].contains("401 lines, cap 400"), "{bad:?}");
    assert!(bad[0].contains("raising a cap needs the owner"), "{bad:?}");
    let shrunk = [("p.rs::big".to_string(), 300), ("p.rs::new#2".to_string(), 300)];
    assert!(violations(&shrunk, &caps).is_empty());
    assert!(lowerable(&shrunk, &caps)[0].contains("lower its cap from 400 to 300"));
}

#[test]
fn a_row_without_a_long_function_fails() {
    let caps = parse_table(TABLE, "\"p.rs::gone\" = 400\n");
    let bad = violations(&[], &caps);
    assert_eq!(bad.len(), 1);
    assert!(bad[0].contains("delete the row"), "{bad:?}");
}
